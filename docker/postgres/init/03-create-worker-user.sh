#!/bin/bash
set -euo pipefail

WORKER_USER="${WORKER_USERNAME:-tinkertaps_worker}"
WORKER_PASS="${WORKER_PASSWORD:-O0ypFEY6CG7vrylK}"

psql -v ON_ERROR_STOP=1 \
    --username "${POSTGRES_USER:-postgres}" \
    --dbname "${POSTGRES_DB}" \
    <<-EOSQL
DO \$\$
BEGIN
  IF NOT EXISTS (
    SELECT
    FROM pg_catalog.pg_roles
    WHERE rolname = '${WORKER_USER}'
  ) THEN
    CREATE ROLE ${WORKER_USER}
      LOGIN
      PASSWORD '${WORKER_PASS}';
  END IF;
END
\$\$;

GRANT CONNECT ON DATABASE ${POSTGRES_DB}
TO ${WORKER_USER};

GRANT USAGE ON SCHEMA public
TO ${WORKER_USER};

GRANT SELECT, UPDATE ON ALL TABLES IN SCHEMA public
TO ${WORKER_USER};

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public
TO ${WORKER_USER};

ALTER DEFAULT PRIVILEGES
FOR ROLE ${MIGRATOR_DB_USER:-tinkertaps_migrator}
IN SCHEMA public
GRANT SELECT, UPDATE ON TABLES
TO ${WORKER_USER};

ALTER DEFAULT PRIVILEGES
FOR ROLE ${MIGRATOR_DB_USER:-tinkertaps_migrator}
IN SCHEMA public
GRANT USAGE, SELECT ON SEQUENCES
TO ${WORKER_USER};
EOSQL
